_T = TypeVar("_T")
_PARAMETER_TYPES = {
    ConstraintType.TEACHER_UNAVAILABLE: TeacherUnavailable,
    ConstraintType.ROOM_UNAVAILABLE: RoomUnavailable,
    ConstraintType.CLASS_UNAVAILABLE: ClassUnavailable,
    ConstraintType.ROOM_FEATURE_REQUIRED: RoomFeatureRequired,
    ConstraintType.MAX_CLASS_PERIODS_PER_DAY: MaxClassPeriodsPerDay,
    ConstraintType.TEACHER_PREFERRED_SLOTS: TeacherPreferredSlots,
    ConstraintType.MINIMIZE_TEACHER_GAPS: MinimizeTeacherGaps,
    ConstraintType.MINIMIZE_CLASS_GAPS: MinimizeClassGaps,
    ConstraintType.BALANCE_CLASS_DAILY_LOAD: BalanceClassDailyLoad,
}


def _schema_error(path: str, message: str) -> AIResponseError:
    return AIResponseError("invalid_schema", path, message)


def _json_object(pairs: list[tuple[str, object]]) -> dict[str, object]:
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("Duplicate JSON member")
        result[key] = value
    return result


def _reject_constant(value: str) -> None:
    raise ValueError("Non-finite JSON number")


def _load(raw_response: str) -> dict[str, object]:
    if not isinstance(raw_response, str):
        raise AIResponseError("invalid_json", "$", "Expected response text.")
    try:
        value = json.loads(
            raw_response,
            object_pairs_hook=_json_object,
            parse_constant=_reject_constant,
        )
    except (ValueError, RecursionError):
        raise AIResponseError("invalid_json", "$", "Expected one strict JSON document.") from None
    return _object(value, "$")


def _object(value: object, path: str) -> dict[str, object]:
    if not isinstance(value, dict):
        raise _schema_error(path, "Expected a JSON object.")
    return value


def _members(
    payload: dict[str, object], *, allowed: set[str], required: set[str], path: str
) -> None:
    if payload.keys() - allowed:
        raise _schema_error(path, "Unexpected object fields.")
    for name in sorted(required - payload.keys()):
        raise _schema_error(f"{path}.{name}", "Required field is missing.")


@lru_cache(maxsize=None)
def _field_types(record_type: type) -> dict[str, object]:
    return get_type_hints(record_type)


def _record(record_type: type[_T], value: object, path: str) -> _T:
    payload = _object(value, path)
    definitions = fields(record_type)
    _members(
        payload,
        allowed={field.name for field in definitions},
        required={
            field.name for field in definitions
            if field.default is MISSING and field.default_factory is MISSING
        },
        path=path,
    )
    hints = _field_types(record_type)
    arguments = {}
    for field in definitions:
        if field.name not in payload:
            continue
        annotation = hints[field.name]
        if record_type is TimetableConstraint and field.name == "parameters":
            annotation = _PARAMETER_TYPES[arguments["type"]]
        arguments[field.name] = _value(annotation, payload[field.name], f"{path}.{field.name}")
    return record_type(**arguments)


def _value(annotation: object, value: object, path: str) -> object:
    origin = get_origin(annotation)
    if origin in (Union, UnionType):
        variants = get_args(annotation)
        if value is None and type(None) in variants:
            return None
        concrete = tuple(item for item in variants if item is not type(None))
        if len(concrete) != 1:
            raise TypeError("Canonical union requires an explicit discriminator")
        return _value(concrete[0], value, path)
    if annotation in (str, int):
        if type(value) is not annotation:
            raise _schema_error(path, "Unexpected JSON scalar type.")
        return value
    if origin is tuple:
        if not isinstance(value, list):
            raise _schema_error(path, "Expected a JSON array.")
        element_type, repeated = get_args(annotation)
        if repeated is not Ellipsis:
            raise TypeError("Canonical collection must be a homogeneous tuple")
        return tuple(_value(element_type, item, f"{path}[{index}]") for index, item in enumerate(value))
    if isinstance(annotation, type) and issubclass(annotation, Enum):
        if not isinstance(value, str):
            raise _schema_error(path, "Expected an enum string.")
        try:
            return annotation(value)
        except ValueError:
            raise _schema_error(path, "Unsupported enum value.") from None
    if isinstance(annotation, type) and is_dataclass(annotation):
        return _record(annotation, value, path)
    raise TypeError("Unsupported canonical field type")


def parse_extraction_response(
    raw_response: str, *, problem: OriginalProblem, model_id: str
) -> ExtractionProposal:
    """Decode domain data, retaining missing information and the exact AI text.

    Absent optional fields use only the defaults already defined by the common
    contract. No domain facts or missing entities are inferred here.
    """
    try:
        payload = _load(raw_response)
        _members(
            payload,
            allowed={"data", "missing_information", "unsupported_requirements"},
            required={"data"},
            path="$",
        )
        data = _record(TimetableData, payload["data"], "$.data")
        missing = _value(
            tuple[MissingInformation, ...], payload.get("missing_information", []),
            "$.missing_information",
        )
        unsupported = _value(
            tuple[str, ...], payload.get("unsupported_requirements", []),
            "$.unsupported_requirements",
        )
        return ExtractionProposal(
            proposal_id=str(uuid4()), problem_id=problem.problem_id, model_id=model_id,
            data=data, missing_information=missing, unsupported_requirements=unsupported,
            raw_response=raw_response,
        )
    except AIResponseError as error:
        error.raw_response = raw_response if isinstance(raw_response, str) else None
        raise


def parse_solution_response(
    raw_response: str, *, snapshot: TimetableProblemSnapshot, model_id: str
) -> TimetableSolution:
    """Decode assignments without repairing or validating timetable feasibility.

    A well-shaped but mathematically invalid solution must remain available to
    the independent verifier. Correlation with another model's snapshot is a
    caller error and is never silently relabelled.
    """
    try:
        if model_id != snapshot.model_id:
            raise AIResponseError("model_mismatch", "$.model_id", "Snapshot belongs to another model.")
        payload = _load(raw_response)
        _members(payload, allowed={"assignments"}, required={"assignments"}, path="$")
        assignments = _value(tuple[LessonAssignment, ...], payload["assignments"], "$.assignments")
        return TimetableSolution(
            solution_id=str(uuid4()), snapshot_id=snapshot.snapshot_id,
            model_id=model_id, assignments=assignments,
        )
    except AIResponseError as error:
        error.raw_response = raw_response if isinstance(raw_response, str) else None
        raise
